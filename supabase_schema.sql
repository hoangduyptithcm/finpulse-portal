('Đồng bộ dữ liệu phân tích doanh nghiệp')
ON CONFLICT DO NOTHING;

-- 8. Cấu hình Row Level Security (RLS) để cho phép đọc dữ liệu công khai qua Supabase API
ALTER TABLE "categories" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "posts" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "tags" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "post_tags" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "todos" ENABLE ROW LEVEL SECURITY;

-- Tạo chính sách cho phép đọc công khai (SELECT)
DROP POLICY IF EXISTS "Cho phép đọc categories công khai" ON "categories";
CREATE POLICY "Cho phép đọc categories công khai" ON "categories" FOR SELECT USING (true);

DROP POLICY IF EXISTS "Cho phép đọc posts đã xuất bản" ON "posts";
CREATE POLICY "Cho phép đọc posts đã xuất bản" ON "posts" FOR SELECT USING (true);

DROP POLICY IF EXISTS "Cho phép đọc tags công khai" ON "tags";
CREATE POLICY "Cho phép đọc tags công khai" ON "tags" FOR SELECT USING (true);

DROP POLICY IF EXISTS "Cho phép đọc post_tags công khai" ON "post_tags";
CREATE POLICY "Cho phép đọc post_tags công khai" ON "post_tags" FOR SELECT USING (true);

DROP POLICY IF EXISTS "Cho phép đọc todos" ON "todos";
CREATE POLICY "Cho phép đọc todos" ON "todos" FOR SELECT USING (true);
